/** Пропорции (width / height) для src. fallback — если файла нет в манифесте. */
export function getAspect(src, fallback = 1) {
  if (typeof src !== "string") return fallback;
  const d = MEDIA_DIMS[src] || MEDIA_DIMS[src.split("?")[0]];
  if (!d) return fallback;
  const [w, h] = d.split("x").map(Number);
  if (!w || !h) return fallback;
  return w / h;
}
